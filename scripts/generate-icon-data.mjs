const WEIGHTS = [400, 500, 600, 700];
const VIEWBOX = "0 -960 960 960";

export function generateIconData() {
  const iconNames = ICON_NAMES;
  const entries = [];

  for (const name of iconNames) {
    for (const weight of WEIGHTS) {
      const svgDir = join(root, "node_modules", "@material-symbols", `svg-${weight}`, "outlined");

      const outlinePath = join(svgDir, `${name}.svg`);
      const outlineSvg = readFileSync(outlinePath, "utf-8");
      const outlineInner = outlineSvg.replace(/<svg[^>]*>/, "").replace(/<\/svg>/, "").trim();
      entries.push(`  "${name}-${weight}": { viewBox: ${JSON.stringify(VIEWBOX)}, paths: ${JSON.stringify(outlineInner)} }`);

      const fillPath = join(svgDir, `${name}-fill.svg`);
      const fillSvg = readFileSync(fillPath, "utf-8");
      const fillInner = fillSvg.replace(/<svg[^>]*>/, "").replace(/<\/svg>/, "").trim();
      entries.push(`  "${name}-fill-${weight}": { viewBox: ${JSON.stringify(VIEWBOX)}, paths: ${JSON.stringify(fillInner)} }`);
    }
  }

  const namesStr = iconNames.map(n => `"${n}"`).join(" | ");

  const output = `// Auto-generated by scripts/generate-icon-data.mjs
// Do not edit directly — edit ICON_NAMES in the generator script and re-run instead.

export type IconData = { viewBox: string; paths: string };

/** @see ICON_NAMES in scripts/generate-icon-data.mjs — add missing names there and re-run. */
export type IconName = ${namesStr};

export const iconData: Record<string, IconData> = {
${entries.join(",\n")},
};
`;

  const outPath = join(root, "src", "utils", "constants", "icon.ts");
  writeFileSync(outPath, output, "utf-8");
  return entries.length;
}

const count = generateIconData();
